// Builds IronRDP's web client from a pinned commit and copies what the RDP console needs into
// vendor/ironrdp. Only needed to update IronRDP; the regular build uses the vendored files.
//
// Requires git, Rust (rustup) and wasm-pack 0.15:
//   rustup target add wasm32-unknown-unknown
//   cargo install wasm-pack --version 0.15.0 --locked
//
//   node scripts/vendor-ironrdp.mjs            build the pinned commit
//   node scripts/vendor-ironrdp.mjs <commit>   build another commit (then update IRONRDP_COMMIT)
//
// Why a source build: VMConnect (Hyper-V) support in the web client (Devolutions/IronRDP#1505)
// is newer than the latest @devolutions/iron-remote-desktop-rdp npm release. Switch to the npm
// packages once a release includes `vmConnect()`.
import { execFileSync } from 'node:child_process';
import { cpSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const IRONRDP_COMMIT = 'ddcffc42c06dc11cd21cf8c9ce2266cd5bdaed9f';
const IRONRDP_REPO = 'https://github.com/Devolutions/IronRDP.git';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const commit = process.argv[2] ?? IRONRDP_COMMIT;
const checkout = path.join(root, '.cache', 'ironrdp');
const vendor = path.join(root, 'vendor', 'ironrdp');

const run = (cmd, args, cwd, env) => execFileSync(cmd, args, { cwd, stdio: 'inherit', env: { ...process.env, ...env } });

if (!existsSync(checkout)) run('git', ['clone', '--filter=blob:none', IRONRDP_REPO, checkout], root);
run('git', ['fetch', '--quiet', 'origin'], checkout);
run('git', ['checkout', '--quiet', '--', '.'], checkout); // drop previously applied patches
run('git', ['-c', 'advice.detachedHead=false', 'checkout', '--quiet', commit], checkout);

// Local patches (see each file's header): applied on top of the pinned commit.
const patchDir = path.join(root, 'scripts', 'ironrdp-patches');
const patches = existsSync(patchDir) ? readdirSync(patchDir).filter((f) => f.endsWith('.patch')).sort() : [];
for (const patch of patches) run('git', ['apply', '--whitespace=nowarn', path.join(patchDir, patch)], checkout);

// Same flags as IronRDP's `cargo xtask web build` (release).
run('wasm-pack', ['build', '--target', 'web'], path.join(checkout, 'crates', 'ironrdp-web'), {
	RUSTFLAGS:
		'-Ctarget-feature=+simd128,+bulk-memory --cfg getrandom_backend="wasm_js" -Copt-level=s -Ccodegen-units=1 -Cllvm-args=-enable-dfa-jump-thread'
});

rmSync(vendor, { recursive: true, force: true });
mkdirSync(path.join(vendor, 'pkg'), { recursive: true });

// wasm-bindgen output. The default wasm location (`new URL(..., import.meta.url)`) is removed so the
// bundler does not emit a second copy: the console passes the wasm URL to init() explicitly.
const pkg = path.join(checkout, 'crates', 'ironrdp-web', 'pkg');
const glue = readFileSync(path.join(pkg, 'ironrdp_web.js'), 'utf8');
const defaultUrl = "new URL('ironrdp_web_bg.wasm', import.meta.url)";
if (!glue.includes(defaultUrl)) throw new Error('Unexpected wasm-bindgen glue: default wasm URL not found');
writeFileSync(
	path.join(vendor, 'pkg', 'ironrdp_web.js'),
	`// Generated by wasm-bindgen from IronRDP ${commit} (crates/ironrdp-web). Do not edit.\n` +
		glue.replace(defaultUrl, "(() => { throw new Error('IronRDP: pass the wasm URL to init()'); })()")
);
for (const file of ['ironrdp_web.d.ts', 'ironrdp_web_bg.wasm']) cpSync(path.join(pkg, file), path.join(vendor, 'pkg', file));

// The protocol-agnostic web component (Svelte 5), without its tests.
cpSync(path.join(checkout, 'web-client', 'iron-remote-desktop', 'src'), path.join(vendor, 'iron-remote-desktop'), {
	recursive: true,
	filter: (source) => !/\.test\.ts$/.test(source) && path.basename(source) !== 'test'
});

for (const file of ['LICENSE-MIT', 'LICENSE-APACHE']) cpSync(path.join(checkout, file), path.join(vendor, file));
writeFileSync(
	path.join(vendor, 'README.md'),
	`# IronRDP (vendored)

Web RDP client used by the in-editor RDP console (Hyper-V VMConnect).

- Source: ${IRONRDP_REPO.replace(/\.git$/, '')} @ \`${commit}\`
- License: MIT OR Apache-2.0 (see LICENSE-MIT, LICENSE-APACHE)
- \`pkg/\`: wasm-pack build of \`crates/ironrdp-web\` (release flags of \`cargo xtask web build\`)
- \`iron-remote-desktop/\`: \`web-client/iron-remote-desktop/src\` (the \`<iron-remote-desktop>\` web component)
- Local patches: ${patches.length ? patches.map((p) => `\`scripts/ironrdp-patches/${p}\``).join(', ') : 'none'}

Regenerate with \`node scripts/vendor-ironrdp.mjs\`. Do not edit these files by hand.
`
);
console.log(`Vendored IronRDP ${commit} into ${path.relative(root, vendor)}`);
